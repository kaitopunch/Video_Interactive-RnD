package com.pion.psremote.core.ui.token

import androidx.compose.ui.unit.dp

/** Every gap on a 4 dp scale. A `.dp` literal in a `padding` or `Spacer` under `feature/` is a defect (MVI doc §11). */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
